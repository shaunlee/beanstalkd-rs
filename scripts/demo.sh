#!/usr/bin/env bash
# One-command demo, no configuration and no client library:
#
#   1. a producer and a worker over the real beanstalkd protocol
#      (put, reserve, delete, bury, stats-tube),
#   2. the Prometheus endpoint,
#   3. SIGTERM, then a restart on the same binlog, with the jobs still there.
#
#   ./scripts/demo.sh                # build if needed, run, clean up
#   BSTK_BIN=/path/to/beanstalkd-rs ./scripts/demo.sh
#   KEEP=1 ./scripts/demo.sh         # leave the server running (prints its ports)
#
# Needs bash, python3 and curl. Nothing outside this repository.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BIN="${BSTK_BIN:-$ROOT/target/release/beanstalkd-rs}"
KEEP="${KEEP:-0}"
OUT="$(mktemp -d "${TMPDIR:-/tmp}/bstk-demo.XXXXXX")"

die() { echo "demo: $*" >&2; exit 1; }
if [ -t 1 ]; then bold=$'\033[1m' reset=$'\033[0m'; else bold="" reset=""; fi
step() { printf '\n%s%s%s\n' "$bold" "$*" "$reset"; }

command -v python3 >/dev/null || die "python3 is required"
command -v curl >/dev/null || die "curl is required"

if [ ! -x "$BIN" ]; then
  echo "demo: building beanstalkd-rs (release)..." >&2
  (cd "$ROOT" && cargo build --release -q -p bstkd)
fi
[ -x "$BIN" ] || die "binary not found at $BIN"

free_port() {
  python3 -c 'import socket; s=socket.socket(); s.bind(("127.0.0.1", 0)); print(s.getsockname()[1])'
}

PORT="$(free_port)"
HTTP_PORT="$(free_port)"
CONF="$OUT/config.toml"
cat >"$CONF" <<EOF
# Generated by scripts/demo.sh.
[[listener]]
addr = "127.0.0.1:$PORT"

[http]
addr = "127.0.0.1:$HTTP_PORT"
EOF

PID=""
cleanup() {
  if [ -n "$PID" ] && [ "$KEEP" != 1 ]; then
    kill "$PID" 2>/dev/null || true
    wait "$PID" 2>/dev/null || true
  fi
  [ "$KEEP" = 1 ] || rm -rf "$OUT"
}
trap cleanup EXIT

start_server() {
  "$BIN" --config "$CONF" -b "$OUT/binlog" "$@" >>"$OUT/server.log" 2>&1 &
  PID=$!
  local i
  for i in $(seq 1 200); do
    curl -fsS "http://127.0.0.1:$HTTP_PORT/readyz" >/dev/null 2>&1 && return 0
    kill -0 "$PID" 2>/dev/null || die "the server exited (see $OUT/server.log)"
    sleep 0.05
  done
  die "the server did not become ready (see $OUT/server.log)"
}

ADDR="127.0.0.1:$PORT"
printf '%s%s%s\n' "$bold" "$("$BIN" -v)" "$reset"
printf 'protocol on %s, HTTP on %s\n' "$ADDR" "127.0.0.1:$HTTP_PORT"
start_server

step "[1/3] the beanstalkd protocol: put, reserve, delete, bury"
python3 "$ROOT/scripts/demo-client.py" flow "$ADDR"

step "[2/3] the same server, as Prometheus sees it"
curl -fsS "http://127.0.0.1:$HTTP_PORT/metrics" >"$OUT/metrics"
grep -E '^beanstalkd_(jobs_total|current_jobs|current_tubes)' "$OUT/metrics" | sed 's/^/  /'
# The per-command counters, minus the commands this demo never sent.
grep -E '^beanstalkd_commands_total' "$OUT/metrics" | grep -v ' 0$' | sed 's/^/  /'
printf '  %-26s%s\n' "/healthz" "$(curl -fsS "http://127.0.0.1:$HTTP_PORT/healthz")"
printf '  %-26s%s\n' "/readyz" "$(curl -fsS -o /dev/null -w '%{http_code}' "http://127.0.0.1:$HTTP_PORT/readyz")"

step "[3/3] SIGTERM, then a restart on the same binlog"
before="$(python3 "$ROOT/scripts/demo-client.py" count "$ADDR")"
kill -TERM "$PID"
wait "$PID" || die "the server did not exit 0 on SIGTERM"
printf '  %-26s%s\n' "SIGTERM" "exit 0, binlog synced"
PID=""
start_server
after="$(python3 "$ROOT/scripts/demo-client.py" count "$ADDR")"
[ "$after" = "$before" ] || die "expected $before ready jobs after the restart, found $after"
printf '  %-26s%s\n' "restart" "counts unchanged after the restart:"
python3 "$ROOT/scripts/demo-client.py" state "$ADDR"

step "done"
if [ "$KEEP" = 1 ]; then
  echo "  server still running: $BIN --config $CONF (pid $PID, protocol $ADDR, HTTP 127.0.0.1:$HTTP_PORT)"
  echo "  stop it with: kill $PID"
else
  echo "  one binary, no runtime dependencies. Clusters, TLS and monitoring:"
  echo "  docs/OPERATIONS.md"
fi
